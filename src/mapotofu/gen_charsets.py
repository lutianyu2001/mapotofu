"""Regenerate data/common-*.txt, the common ideographs of each region (PLAN 3).

SC: the Table of General Standard Chinese Characters (Unihan kTGH) plus every other ideograph
seen at least 300 times in the FineWeb-2 Chinese counts of rime-lm. TC: Big5 (kBigFive).
J: JIS X 0208 and JIS X 0213 (kJis0, kJIS0213).

    python -m mapotofu.gen_charsets ../rime-lm/data/fw2-v2/counts.json
"""

from __future__ import annotations

import collections
import json
import sys
import zipfile

from .charsets import Cat, category
from .config import DATA, SOURCES

SC_MIN_COUNT = 300


def main() -> None:
    counts = json.loads(open(sys.argv[1]).read())["counts"]
    fields = collections.defaultdict(set)
    with zipfile.ZipFile(SOURCES / "_cache" / "Unihan.zip") as z:
        for name in z.namelist():
            for line in z.read(name).decode().splitlines():
                if line.startswith("U+"):
                    cp, key, _ = line.split("\t", 2)
                    if key in ("kTGH", "kBigFive", "kJis0", "kJIS0213", "kTotalStrokes"):
                        fields[key].add(int(cp[2:], 16))
    unihan = fields["kTotalStrokes"]
    frequent = {ord(ch) for ch, n in counts.items() if len(ch) == 1 and n >= SC_MIN_COUNT}
    sets = {
        "sc": fields["kTGH"] | (frequent & unihan),
        "tc": fields["kBigFive"],
        "j": fields["kJis0"] | fields["kJIS0213"],
    }
    DATA.mkdir(exist_ok=True)
    for region, cps in sets.items():
        assert all(category(cp) is Cat.IDEO for cp in cps)
        lines = [f"# Common ideographs of {region.upper()}, generated by mapotofu.gen_charsets"]
        lines += [f"{cp:04X}\t{chr(cp)}" for cp in sorted(cps)]
        (DATA / f"common-{region}.txt").write_text("\n".join(lines) + "\n")
        print(region, len(cps))


if __name__ == "__main__":
    main()
